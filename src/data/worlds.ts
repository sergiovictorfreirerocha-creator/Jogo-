export function getWorldById(id: WorldId): WorldDef {
  return WORLDS.find((w) => w.id === id) || WORLDS[0];
}

export function getNextWorldId(id: WorldId): WorldId | null {
  const idx = WORLDS.findIndex((w) => w.id === id);
  if (idx >= 0 && idx < WORLDS.length - 1) {
    return WORLDS[idx + 1].id;
  }
  return null;
}
